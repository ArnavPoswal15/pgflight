#!/usr/bin/env bash
# Measure pgbench latency direct (:5432) vs proxied (:5433); write docs/benchmarks/overhead.md + JSON.
# SLO target: <0.3ms added p99 on the proxy path (target, not a guarantee).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT_DIR="$ROOT/docs/benchmarks"
OUT_MD="$OUT_DIR/overhead.md"
OUT_JSON="$OUT_DIR/overhead.json"
# shellcheck source=lib_pgflightd.sh
source "$ROOT/scripts/lib_pgflightd.sh"

LISTEN="${PGFLIGHT_LISTEN:-127.0.0.1:5433}"
UPSTREAM="${PGFLIGHT_UPSTREAM:-127.0.0.1:5432}"
DIRECT_URL="postgresql://postgres:postgres@${UPSTREAM}/shop"
PROXY_URL="postgresql://postgres:postgres@${LISTEN}/shop"
SLO_TARGET_MS="0.3"

skip() {
  echo "$1"
  exit 0
}

if ! command -v pgbench >/dev/null 2>&1; then
  skip "pgbench not found; skipping overhead measurement (exit 0)."
fi

if ! command -v docker >/dev/null 2>&1; then
  skip "docker not found; skipping overhead measurement (exit 0)."
fi

if ! docker info >/dev/null 2>&1; then
  skip "docker daemon not running; skipping overhead measurement (exit 0)."
fi

mkdir -p "$OUT_DIR"
TMP_DIRECT="$(mktemp)"
TMP_PROXY="$(mktemp)"
trap 'rm -f "$TMP_DIRECT" "$TMP_PROXY"; stop_pgflightd_if_started' EXIT

docker compose -f "$ROOT/docker/docker-compose.yml" up -d --wait

start_or_reuse_pgflightd "$ROOT" "$LISTEN" "$UPSTREAM"

echo "==> pgbench direct ($UPSTREAM)"
pgbench -i -s 1 "$DIRECT_URL" >/dev/null
pgbench -c 16 -T 15 -P 1 "$DIRECT_URL" | tee "$TMP_DIRECT"

echo "==> pgbench proxied ($LISTEN)"
pgbench -c 16 -T 15 -P 1 "$PROXY_URL" | tee "$TMP_PROXY"

parse_latency_ms() {
  local file="$1"
  if grep -qE 'p99[[:space:]]*=' "$file" 2>/dev/null; then
    grep -E 'p99[[:space:]]*=' "$file" | tail -1 | sed -E 's/.*p99[[:space:]]*=[[:space:]]*([0-9.]+).*/\1/'
    return
  fi
  if grep -qE 'latency average = ' "$file" 2>/dev/null; then
    grep -E 'latency average = ' "$file" | tail -1 | sed -E 's/.*latency average = ([0-9.]+).*/\1/'
    return
  fi
  echo "null"
}

DIRECT_MS="$(parse_latency_ms "$TMP_DIRECT")"
PROXY_MS="$(parse_latency_ms "$TMP_PROXY")"

DELTA="null"
USED_P99="false"
if grep -qE 'p99[[:space:]]*=' "$TMP_DIRECT" 2>/dev/null; then
  USED_P99="true"
fi

if [[ "$DIRECT_MS" != "null" && "$PROXY_MS" != "null" ]]; then
  DELTA="$(awk -v d="$DIRECT_MS" -v p="$PROXY_MS" 'BEGIN { printf "%.6f", p - d }')"
fi

MEASURED_AT="$(date -u +"%Y-%m-%dT%H:%M:%SZ")"

json_num() {
  local v="$1"
  if [[ "$v" == "null" ]]; then
    echo "null"
  else
    echo "$v"
  fi
}

cat >"$OUT_JSON" <<EOF
{
  "measured_at": "$MEASURED_AT",
  "direct_latency_ms": $(json_num "$DIRECT_MS"),
  "proxy_latency_ms": $(json_num "$PROXY_MS"),
  "proxy_minus_direct_ms": $(json_num "$DELTA"),
  "slo_target_added_p99_ms": $SLO_TARGET_MS,
  "slo_is_guarantee": false,
  "used_p99_line": $USED_P99,
  "pgbench": {
    "clients": 16,
    "duration_sec": 15
  }
}
EOF

{
  echo "# Proxy overhead (pgbench)"
  echo
  echo "Generated by \`scripts/bench-overhead.sh\` at **${MEASURED_AT}**."
  echo
  echo "| Path | Latency (ms) |"
  echo "|------|----------------|"
  echo "| Direct (\`${UPSTREAM}\`) | ${DIRECT_MS} |"
  echo "| Proxied (\`${LISTEN}\`) | ${PROXY_MS} |"
  echo "| **Added (proxy − direct)** | **${DELTA}** |"
  echo
  if [[ "$USED_P99" == "true" ]]; then
    echo "Parser used **p99** lines from pgbench output."
  else
    echo "Parser fell back to **latency average** (p99 line not found in output)."
  fi
  echo
  echo "**SLO target:** added p99 &lt; **${SLO_TARGET_MS} ms** on the proxy path — a **target**, not a guarantee."
  echo
  echo "Machine-local numbers; re-run the script to refresh. See also \`overhead.json\`."
} >"$OUT_MD"

echo "==> Wrote $OUT_MD and $OUT_JSON"
if [[ "$DELTA" != "null" ]]; then
  echo "==> Proxy minus direct: ${DELTA} ms (SLO target < ${SLO_TARGET_MS} ms added p99)"
fi